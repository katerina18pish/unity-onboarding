using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class Platform : MonoBehaviour
{
    //Скорость движения платформы
    public float speed;
    //Направление движения платформы
    public Vector3 direction;
    //Состояние платформы: активна / не активна
    public bool isActive;


    //Обновление движения платформы каждый кадр
    void Update()
    {
        if (isActive)
        {
            transform.position += direction * speed * Time.deltaTime;
        }
    }


    //Столкновение платформы с двумя типами объектов
    void OnTriggerEnter(Collider other) {
        /*Если платформа достигает точки остановки, то она меняет направление
        своего движения*/
        if (other.tag == "PlatformStop")
        {
            direction *= -1;
        }
        //Если платформы коснулся игрок, то она активируется
        if(other.tag == "Player")
        {
            isActive = true;
        }
    }

    void OnTriggerExit(Collider other) {
        //Если с платформы ушёл игрок, то она дезактивируется
        if (other.tag == "Player")
        {
            isActive = false;
        }
    }

}





using System.Collections;              // ← Подключаем библиотеки Unity
using System.Collections.Generic;      // ← (коллекции для списков, массивов)
using UnityEngine;                     // ← Основная библиотека Unity

public class Platform : MonoBehaviour  // ← Класс Platform наследуется от MonoBehaviour
{                                      //   (все скрипты Unity наследуются от MonoBehaviour)

    // ═══════════════════════════════════════════════════════════════
    // ПЕРЕМЕННЫЕ (видны в Inspector)
    // ═══════════════════════════════════════════════════════════════

    public float speed;                // ← Скорость движения (например, 3 = 3 единицы в секунду)
                                       //   public = видно в Inspector и других скриптах
                                       //   float = число с дробной частью (2.5, 3.14)

    public Vector3 direction;          // ← Направление движения в 3D пространстве
                                       //   Vector3 = вектор (x, y, z)
                                       //   (1, 0, 0) = вправо
                                       //   (-1, 0, 0) = влево
                                       //   (0, 1, 0) = вверх

    public bool isActive;              // ← Двигается ли платформа сейчас
                                       //   bool = логическая переменная (true/false)
                                       //   true = двигается, false = стоит

    

    void Update()                      // ← void = метод ничего не возвращает
    {                                  //   Update() = специальный метод Unity, вызывается каждый кадр

        if (isActive)                  // ← Если платформа активна (isActive = true)
        {                              //   то выполняем код внутри { }

            // Двигаем платформу
            transform.position += direction * speed * Time.deltaTime;
            // ↑              ↑   ↑         ↑ ↑     ↑ ↑
            // │              │   │         │ │     │ Время между кадрами (0.016 при 60 FPS)
            // │              │   │         │ │     └─ Делает движение плавным на любом компьютере
            // │              │   │         │ └─ Умножаем на скорость (например, 3)
            // │              │   │         └─ Умножаем на направление ((1,0,0) = вправо)
            // │              │   └─ Прибавляем к текущей позиции (+=)
            // │              └─ Текущая позиция платформы
            // └─ transform = компонент Transform (позиция, поворот, масштаб объекта)

            
        }
    }

    // ═══════════════════════════════════════════════════════════════
    // МЕТОД OnTriggerEnter - вызывается, когда что-то ВХОДИТ в триггер
    // ═══════════════════════════════════════════════════════════════
    // ВАЖНО: На платформе должен быть Collider с галочкой "Is Trigger"!

    void OnTriggerEnter(Collider other)  // ← Collider other = объект, который коснулся
    {                                    //   other = "другой объект"

        // ───────────────────────────────────────────────────────────
        // СИТУАЦИЯ 1: Платформа достигла точки остановки
        // ───────────────────────────────────────────────────────────

        if (other.tag == "PlatformStop") // ← Проверяем тег объекта
        {                                //   other.tag = тег объекта, который коснулся
                                         //   "PlatformStop" = название тега точки остановки
                                         //   == означает "равно"

            direction *= -1;             // ← Меняем направление на противоположное
                                         // ↑        ↑  ↑
                                         // │        │  └─ Минус один
                                         // │        └─ Умножаем и присваиваем (*=)
                                         // └─ Направление

            // Пример:
            // Было: direction = (1, 0, 0) - вправо
            // Стало: direction = (-1, 0, 0) - влево
            // Было: direction = (-1, 0, 0) - влево
            // Стало: direction = (1, 0, 0) - вправо
        }

        // ───────────────────────────────────────────────────────────
        // СИТУАЦИЯ 2: Игрок наступил на платформу
        // ───────────────────────────────────────────────────────────

        if (other.tag == "Player")        // ← Проверяем: это игрок?
        {                                //   У объекта Player должен быть тег "Player"!

            isActive = true;             // ← Активируем платформу (начинает двигаться)
                                         //   Теперь в Update() проверка if (isActive) будет true
        }
    }

    // ═══════════════════════════════════════════════════════════════
    // МЕТОД OnTriggerExit - вызывается, когда что-то ВЫХОДИТ из триггера
    // ═══════════════════════════════════════════════════════════════

    void OnTriggerExit(Collider other)   // ← Collider other = объект, который ушёл
    {

        if (other.tag == "Player")       // ← Проверяем: игрок сошёл?
        {

            isActive = false;            // ← Деактивируем платформу (перестаёт двигаться)
                                         //   Теперь в Update() проверка if (isActive) будет false
        }
    }

} // ← Конец класса Platform