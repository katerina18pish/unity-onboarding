using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class Coin : MonoBehaviour
{
    void OnTriggerEnter(Collider other) {

        CoinsCounter coins = other.GetComponent<CoinsCounter>();

        //Количество монеток обновляется
        coins.CollectCoins();

        //Монетка, которую собрали, уничтожается
        Destroy(gameObject);
    }
}


using System.Collections;              // ← Подключаем библиотеки
using System.Collections.Generic;
using UnityEngine;

public class Coin : MonoBehaviour      // ← Класс Coin (монетка)
{
    // ═══════════════════════════════════════════════════════════════
    // МЕТОД OnTriggerEnter: ИГРОК СОБИРАЕТ МОНЕТКУ
    // ═══════════════════════════════════════════════════════════════
    // ВАЖНО: На монетке должен быть Collider с галочкой "Is Trigger"!

    void OnTriggerEnter(Collider other)  // ← Collider other = объект, который коснулся
    {

        // ───────────────────────────────────────────────────────────
        // ПОИСК МОДУЛЯ COINSCOUNTER НА ОБЪЕКТЕ
        // ───────────────────────────────────────────────────────────
        // КАК БЫЛО РАНЬШЕ (когда был один Player.cs):
        // Player player = other.GetComponent<Player>();
        // player.coins++;
        //
        // КАК СТАЛО (модульная система):
        // Ищем модуль CoinsCounter и вызываем метод CollectCoins

        CoinsCounter coins = other.GetComponent<CoinsCounter>();
        // ↑           ↑      ↑     ↑               ↑
        // │           │      │     │               └─ <CoinsCounter> = тип модуля
        // │           │      │     └─ GetComponent = поиск компонента на объекте
        // │           │      └─ other = объект, который коснулся монетки (игрок)
        // │           └─ coins = переменная для хранения найденного модуля
        // └─ CoinsCounter = тип переменной (модуль счётчика монет)
        //
        // Что происходит:
        // 1. other = объект, который коснулся монетки (например, Player)
        // 2. GetComponent<CoinsCounter>() ищет на нём модуль CoinsCounter
        // 3. Если нашёл → записывает в переменную coins
        // 4. Если не нашёл → coins будет null (пусто)
        //
        // Пример:
        // Player коснулся монетки → GetComponent найдёт CoinsCounter → coins = ссылка
        // Враг коснулся монетки → GetComponent не найдёт CoinsCounter → coins = null

        // ───────────────────────────────────────────────────────────
        // ПРОВЕРКА НА NULL (ДОБАВЛЕНА!)
        // ───────────────────────────────────────────────────────────
        // ⚠️ ВАЖНО: В ИСХОДНОМ КОДЕ ЭТОЙ ПРОВЕРКИ НЕ БЫЛО!
        // Это могло вызвать ошибку "NullReferenceException"
        //
        // Проблема без проверки:
        // Если монетку коснётся враг (у которого нет CoinsCounter),
        // то coins будет null
        // Строка coins.CollectCoins() вызовет ошибку
        // "Нельзя вызвать метод у пустой переменной!"
        //
        // Решение: Проверяем, что coins не null

        if (coins != null)               // ← Проверяем: модуль CoinsCounter найден?
        {                                //   != null означает "не равно null"
                                         //   Если найден → выполняем код внутри { }
                                         //   Если не найден → пропускаем

            // ───────────────────────────────────────────────────────
            // УВЕЛИЧЕНИЕ СЧЁТЧИКА МОНЕТ
            // ───────────────────────────────────────────────────────

            coins.CollectCoins();
            // ↑    ↑
            // │    └─ CollectCoins() = метод из модуля CoinsCounter
            // │       (увеличивает счётчик на 1)
            // └─ coins = ссылка на модуль CoinsCounter (нашли выше)
            //
            // Что происходит:
            // Вызываем метод CollectCoins у модуля CoinsCounter
            // Говорим: "Эй, CoinsCounter! Игрок собрал монетку!"
            // CoinsCounter сам разберётся:
            // - Увеличит переменную coins на 1 (coins++)
            // - PlayerUI автоматически увидит изменение и обновит экран
            //
            // ПРЕИМУЩЕСТВО МОДУЛЬНОСТИ:
            // Монетка не знает, что происходит дальше
            // Она просто говорит: "Собрали монетку"
            // CoinsCounter обновляет счётчик
            // PlayerUI показывает на экране
            // Монетка не думает ни про счётчик, ни про UI

            // ───────────────────────────────────────────────────────
            // УНИЧТОЖЕНИЕ МОНЕТКИ
            // ───────────────────────────────────────────────────────

            Destroy(gameObject);
            // ↑      ↑
            // │      └─ gameObject = этот объект (монетка)
            // └─ Destroy = метод Unity для уничтожения объекта
            //
            // Что происходит:
            // Unity удаляет монетку со сцены
            // Монетка исчезает, игрок больше не может её собрать
            //
            // Почему монетка сама себя уничтожает?
            // Это правильный подход - каждый объект отвечает за свою "жизнь"
            // Монетка знает: "Меня собрали → я должна исчезнуть"
        }
    }

} // ← Конец класса Coin



