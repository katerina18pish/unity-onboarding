using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class Bonfire : MonoBehaviour
{
	//Время жизни огня
	public float lifeTime = 15;
	//Теплоотдача
	public float heatPower = 0.1f;

	//Каждый кадр костёр постепенно угасает, затем исчезает со сцены
	void Update()
	{
		lifeTime -= Time.deltaTime;
		if (lifeTime <= 0)
		{
			gameObject.SetActive(false);
		}
	}

	void OnTriggerStay(Collider other)
	{
		if (other.GetComponent<Temperature>() != null)
		{
			Temperature temperature = other.GetComponent<Temperature>();
			// Если температура тела игрока меньше нормальной, то согреваем его
			if (temperature.temperatureCurrent < temperature.temperatureNormal)
			{
				temperature.temperatureCurrent += heatPower * Time.deltaTime;
			}
		}
	}
}


using System.Collections;              // ← Подключаем библиотеки
using System.Collections.Generic;
using UnityEngine;

public class Bonfire : MonoBehaviour   // ← Класс Bonfire (костёр)
{
    // ═══════════════════════════════════════════════════════════════
    // ПЕРЕМЕННЫЕ КОСТРА
    // ═══════════════════════════════════════════════════════════════

    public float lifeTime = 15;        // ← Время жизни костра (15 секунд)
                                       //   float = число с дробной частью
                                       //   Костёр горит 15 секунд, потом гаснет

    public float heatPower = 0.1f;     // ← Теплоотдача (насколько быстро согревает)
                                       //   0.1 градусов в секунду
                                       //   За 10 секунд согреет на 1 градус

    // ═══════════════════════════════════════════════════════════════
    // МЕТОД UPDATE: УГАСАНИЕ КОСТРА
    // ═══════════════════════════════════════════════════════════════

    void Update()                      // ← Вызывается каждый кадр
    {

        lifeTime -= Time.deltaTime;    // ← Уменьшаем время жизни костра
                                       // ↑       ↑  ↑
                                       // │       │  └─ Время между кадрами (0.016 при 60 FPS)
                                       // │       └─ -= означает "отнять и присвоить"
                                       // └─ lifeTime = оставшееся время жизни
                                       //
                                       // Каждый кадр отнимаем время
                                       // lifeTime = 15.0
                                       // Через 1 кадр: 15.0 - 0.016 = 14.984
                                       // Через 1 секунду: 15.0 - 1.0 = 14.0
                                       // Через 15 секунд: 15.0 - 15.0 = 0

        if (lifeTime <= 0)             // ← Если время жизни закончилось
        {                              //   <= означает "меньше или равно"

            gameObject.SetActive(false);
            // ↑         ↑        ↑
            // │         │        └─ false = выключить
            // │         └─ SetActive = метод Unity (включить/выключить объект)
            // └─ gameObject = этот объект (костёр)
            //
            // Что происходит:
            // Костёр выключается (но не удаляется!)
            // SetActive(false) = объект остаётся в сцене, но невидим и неактивен
            // Его можно снова включить SetActive(true)
            //
            // Почему не Destroy?
            // SetActive быстрее и можно переиспользовать объект
            // Но можно использовать и Destroy(gameObject) для полного удаления
        }
    }

    // ═══════════════════════════════════════════════════════════════
    // МЕТОД OnTriggerStay: ИГРОК СТОИТ У КОСТРА
    // ═══════════════════════════════════════════════════════════════
    // ВАЖНО: На костре должен быть Collider с галочкой "Is Trigger"!
    //
    // OnTriggerStay вызывается КАЖДЫЙ КАДР, пока объект ВНУТРИ триггера
    // Отличие от OnTriggerEnter:
    // - OnTriggerEnter = один раз при входе
    // - OnTriggerStay = каждый кадр пока внутри
    // - OnTriggerExit = один раз при выходе

    void OnTriggerStay(Collider other) // ← Collider other = объект внутри триггера
    {

        // ───────────────────────────────────────────────────────────
        // ПРОВЕРКА: ЕСТЬ ЛИ У ОБЪЕКТА МОДУЛЬ TEMPERATURE?
        // ───────────────────────────────────────────────────────────

        if (other.GetComponent<Temperature>() != null) // ← Проверяем наличие Temperature
        {                                //   GetComponent<Temperature>() = ищет модуль
                                         //   != null = не равно null (модуль найден)

            // У объекта есть Temperature → это игрок, согреваем его!

            // ───────────────────────────────────────────────────────
            // ПОЛУЧЕНИЕ МОДУЛЯ TEMPERATURE
            // ───────────────────────────────────────────────────────

            Temperature temperature = other.GetComponent<Temperature>();
            // ↑          ↑            ↑     ↑               ↑
            // │          │            │     │               └─ <Temperature> = тип модуля
            // │          │            │     └─ GetComponent = поиск модуля
            // │          │            └─ other = объект в триггере (игрок)
            // │          └─ temperature = переменная для хранения модуля
            // └─ Temperature = тип переменной (модуль температуры)
            //
            // Находим модуль Temperature на игроке
            // Теперь можем читать и менять температуру!

            // ───────────────────────────────────────────────────────
            // ПРОВЕРКА: НУЖНО ЛИ СОГРЕВАТЬ?
            // ───────────────────────────────────────────────────────

            if (temperature.temperatureCurrent < temperature.temperatureNormal)
            {          // ↑                     ↑ ↑                   
                       // │                     │ └─ temperatureNormal = 36.6 (норма)
                       // │                     └─ < означает "меньше"
                       // └─ temperatureCurrent = текущая температура
                       //
                       // Если текущая температура < нормальной (например, 35 < 36.6)
                       // → согреваем игрока

                temperature.temperatureCurrent += heatPower * Time.deltaTime;
                // ↑          ↑                  ↑  ↑          ↑ ↑
                // │          │                  │  │          │ └─ Время между кадрами
                // │          │                  │  │          └─ Умножаем на теплоотдачу
                // │          │                  │  └─ heatPower = 0.1 (градусов в секунду)
                // │          │                  └─ += означает "прибавить и присвоить"
                // │          └─ temperatureCurrent = текущая температура
                // └─ temperature = ссылка на модуль Temperature (нашли выше)
                //
                // Каждый кадр прибавляем немного тепла
                // heatPower * Time.deltaTime = 0.1 * 0.016 = 0.0016 градусов за кадр
                // За 1 секунду (60 кадров): 0.0016 * 60 = 0.096 ≈ 0.1 градусов
                //
                // Пример:
                // Игрок стоит у костра с температурой 35°
                // Через 1 секунду: 35 + 0.1 = 35.1
                // Через 10 секунд: 35 + 1.0 = 36.0
                // Через 16 секунд: 35 + 1.6 = 36.6 (норма!)
                //
                // Когда температура достигнет 36.6, проверка станет false
                // Согревание остановится (температура не поднимется выше нормы)
            }
        }
    }

} // ← Конец класса Bonfire