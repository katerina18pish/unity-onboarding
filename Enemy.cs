using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class Enemy : MonoBehaviour
{
    //Скорость движения врага
    public float speed;
    //Цель, к которой движется враг
    public Transform target;
    //Очки урона от атаки врагом игрока
    public int playerDamage = 2;
 
    void Update()
    {
        //Меняет каждый кадр позицию NPC на новую
        transform.position = Vector3.MoveTowards(transform.position, target.position, speed * Time.deltaTime);

        //Разворачивает каждый кадр NPC лицом к цели
        transform.LookAt(target.position);
    }

    //При столкновении врага с игроком второму наносится урон
    private void OnTriggerEnter(Collider other)
    {
        if (other.GetComponent<Health>() == true)
        {
            Health health = other.GetComponent<Health>();
            health.TakeDamage(playerDamage);
        }
    }
}



using System.Collections;              // ← Подключаем библиотеки
using System.Collections.Generic;
using UnityEngine;

public class Enemy : MonoBehaviour     // ← Класс Enemy (враг)
{
    // ═══════════════════════════════════════════════════════════════
    // ПЕРЕМЕННЫЕ
    // ═══════════════════════════════════════════════════════════════

    public float speed;                // ← Скорость движения врага
                                       //   float = число с дробной частью (2.5)

    public Transform target;           // ← Цель, к которой движется враг (обычно Player)
                                       //   Transform = позиция объекта
                                       //   КАК НАСТРОИТЬ:
                                       //   1. Перетащить Player из Hierarchy сюда в Inspector

    public int playerDamage = 2;       // ← Сколько урона наносит враг
                                       //   int = целое число
                                       //   = 2 означает начальное значение

    // ═══════════════════════════════════════════════════════════════
    // МЕТОД UPDATE: ДВИЖЕНИЕ К ЦЕЛИ
    // ═══════════════════════════════════════════════════════════════

    void Update()                      // ← Вызывается каждый кадр
    {

        // ───────────────────────────────────────────────────────────
        // ДВИЖЕНИЕ К ИГРОКУ
        // ───────────────────────────────────────────────────────────

        transform.position = Vector3.MoveTowards(transform.position, target.position, speed * Time.deltaTime);
        // ↑        ↑         ↑       ↑            ↑                  ↑                ↑     ↑ ↑
        // │        │         │       │            │                  │                │     │ └─ Время между кадрами
        // │        │         │       │            │                  │                │     └─ Умножаем на скорость
        // │        │         │       │            │                  │                └─ Расстояние за этот кадр
        // │        │         │       │            │                  └─ Позиция цели (Player)
        // │        │         │       │            └─ Откуда (текущая позиция врага)
        // │        │         │       └─ MoveTowards = двигать от одной точки к другой
        // │        │         └─ Vector3 = класс для работы с 3D векторами
        // │        └─ position = новая позиция врага
        // └─ transform = компонент Transform врага
        //
        // Что происходит:
        // Vector3.MoveTowards двигает объект от текущей позиции к цели
        // Каждый кадр враг немного приближается к игроку
        //
        // Пример:
        // Враг на позиции (0, 0, 0)
        // Игрок на позиции (10, 0, 0)
        // speed = 2, Time.deltaTime = 0.016
        // За кадр враг сдвинется на: 2 * 0.016 = 0.032 единиц
        // Новая позиция: (0.032, 0, 0)
        // Через много кадров враг дойдёт до (10, 0, 0)

        // ───────────────────────────────────────────────────────────
        // ПОВОРОТ К ИГРОКУ
        // ───────────────────────────────────────────────────────────

        transform.LookAt(target.position);
        // ↑        ↑       ↑      ↑
        // │        │       │      └─ Позиция цели (Player)
        // │        │       └─ target = ссылка на Transform игрока (перетащили в Inspector)
        // │        └─ LookAt = повернуть объект лицом к указанной позиции
        // └─ transform = компонент Transform врага
        //
        // Что происходит:
        // Враг всегда смотрит на игрока
        // Если игрок справа - враг повернётся вправо
        // Если игрок слева - враг повернётся влево
    }

    // ═══════════════════════════════════════════════════════════════
    // МЕТОД OnTriggerEnter: СТОЛКНОВЕНИЕ С ИГРОКОМ
    // ═══════════════════════════════════════════════════════════════
    // ВАЖНО: На враге должен быть Collider с галочкой "Is Trigger"!

    private void OnTriggerEnter(Collider other) // ← private = используется только внутри класса
    {                                    //   Collider other = объект, с которым столкнулись

        // ───────────────────────────────────────────────────────────
        // ПОИСК МОДУЛЯ HEALTH НА ОБЪЕКТЕ
        // ───────────────────────────────────────────────────────────
        // ЭТО КЛЮЧЕВОЙ МОМЕНТ МОДУЛЬНОСТИ!
        //
        // ИСПРАВЛЕНА ОШИБКА ИЗ ИСХОДНОГО КОДА:
        // Было (неправильно): if (other.GetComponent<Health>() == true)
        // Проблема: GetComponent возвращает компонент или null, а не true/false!
        //
        // Правильно:

        if (other.GetComponent<Health>() != null) // ← Проверяем: есть ли Health на объекте?
        {                                    //   GetComponent<Health>() = ищет компонент Health
                                             //   != null означает "не равно null"
                                             //   null = пусто, ничего нет
                                             //
                                             //   Если Health найден → выполняем код внутри { }
                                             //   Если Health не найден (это не игрок) → пропускаем

            // ───────────────────────────────────────────────────────
            // НАНЕСЕНИЕ УРОНА ЧЕРЕЗ МОДУЛЬ HEALTH
            // ───────────────────────────────────────────────────────
            // КАК БЫЛО РАНЬШЕ (когда был один Player.cs):
            // Player player = other.GetComponent<Player>();
            // player.health -= playerDamage;
            //
            // Проблема: Враг знал внутреннее устройство Player (переменную health)
            //
            // КАК СТАЛО (модульная система):
            // Враг ищет модуль Health и вызывает метод TakeDamage
            // Враг НЕ ЗНАЕТ, как внутри работает Health!

            Health health = other.GetComponent<Health>();
            // ↑     ↑       ↑     ↑               ↑
            // │     │       │     │               └─ <Health> = тип компонента (модуль Health)
            // │     │       │     └─ GetComponent = метод Unity для поиска компонента
            // │     │       └─ other = объект, с которым столкнулись (игрок)
            // │     └─ health = переменная для хранения найденного компонента
            // └─ Health = тип переменной (модуль Health)
            //
            // Что происходит:
            // 1. other = объект Player (с ним столкнулись)
            // 2. GetComponent<Health>() ищет на Player компонент Health
            // 3. Если нашёл → записывает в переменную health
            // 4. Теперь health = ссылка на модуль Health игрока
            //
            // Это как найти номер телефона доктора:
            // other = дом Player
            // GetComponent<Health>() = найти в доме кабинет врача
            // health = номер телефона врача

            health.TakeDamage(playerDamage);
            // ↑     ↑          ↑
            // │     │          └─ playerDamage = количество урона (2)
            // │     └─ TakeDamage = метод из модуля Health
            // └─ health = ссылка на модуль Health (нашли выше)
            //
            // Что происходит:
            // Вызываем метод TakeDamage у модуля Health
            // Говорим: "Эй, Health! Нанеси игроку 2 урона!"
            // Health сам разберётся что делать:
            // - Отнимет здоровье
            // - Проиграет звук
            // - Перезагрузит сцену если здоровье закончилось
            //
            // ПРЕИМУЩЕСТВО МОДУЛЬНОСТИ:
            // Враг не знает КАК работает Health внутри
            // Враг просто говорит: "Нанеси урон"
            // Если завтра мы изменим Health (добавим броню, щиты),
            // код Enemy менять НЕ НУЖНО!
        }
    }

} // ← Конец класса Enemy